-- The items keyed by a number of the application's own: a primary key of one number is the key H2 keeps a table's
-- rows by, so an item read by it is one tree of the file, not the index of the site's id and then the row. The site's
-- id beside it, unique. Its texts become columns of its row (V38, the source's own migrations name them): read with
-- the row, not a row of item_text and a LOB each. Filled by V38, put in the place of item by V39.
CREATE TABLE item_new(
    internal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id CHARACTER VARYING(200) NOT NULL,
    url CHARACTER VARYING(2000) NOT NULL,
    title CHARACTER VARYING(1000) NOT NULL,
    version CHARACTER VARYING(500) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    text_words INTEGER,
    text_chars INTEGER,
    text_letters_1 INTEGER,
    text_letters_2 INTEGER,
    text_letters_3 INTEGER,
    text_punctuation_1 INTEGER,
    text_punctuation_2 INTEGER,
    text_spaces INTEGER,
    text_breaks INTEGER,
    text_other INTEGER,
    changed_at TIMESTAMP WITH TIME ZONE,
    data_at TIMESTAMP WITH TIME ZONE,
    chapters_at TIMESTAMP WITH TIME ZONE,
    reviews_at TIMESTAMP WITH TIME ZONE,
    pictures_at TIMESTAMP WITH TIME ZONE
);
