-- A normalized author: a writer of the user's, whatever accounts the sites know them by
CREATE TABLE normalized_author (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

-- Every author of every site — the site's own key of them — and the normalized author they are: at
-- first one of their own, never by the likeness of a name; merged by the user, on the evidence of
-- their works. Several authors of one site may be one normalized author
CREATE TABLE site_author (
    source     VARCHAR(100)             NOT NULL,
    author     VARCHAR(500)             NOT NULL,
    normalized BIGINT                   NOT NULL REFERENCES normalized_author (id),
    bound_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, author)
);
CREATE INDEX site_author_normalized ON site_author (normalized);

-- Two normalized authors the user told apart: never offered as one again; the smaller id first
CREATE TABLE normalized_author_distinct (
    first_author BIGINT                   NOT NULL REFERENCES normalized_author (id) ON DELETE CASCADE,
    other_author BIGINT                   NOT NULL REFERENCES normalized_author (id) ON DELETE CASCADE,
    said_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (first_author, other_author)
);
