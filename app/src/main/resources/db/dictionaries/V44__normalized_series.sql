-- THE NORMALIZED SERIES (owner, 2026-11-27: "the series are an entity of the same order as the authors, the works, the
-- fandoms, the tags"; "the key of a normalized series is an artificial identifier"): the series of the sites sharing a
-- normalized work, with the works the user said to be one series (series_group), are one series — as series.SeriesJoin
-- joins them —, kept by its number and made anew by the keys of the works it changes of (series.SeriesBinding). Of
-- every one: its content type; when the list of its works last changed (works_at); what its list is filtered and
-- ordered by — its title (of its first series of a site, or of its first work), every title it is known by, how many
-- works and sites it has, whether the user's word holds it together, whether a page of a series of a site of it is to
-- be visited
CREATE TABLE normalized_series (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_type VARCHAR(100)             NOT NULL,
    works_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    title        VARCHAR(1000)            NOT NULL,
    titles       VARCHAR(4000)            NOT NULL,
    works        INT                      NOT NULL,
    sites        INT                      NOT NULL,
    by_hand      BOOLEAN                  NOT NULL,
    to_visit     BOOLEAN                  NOT NULL
);
CREATE INDEX normalized_series_list ON normalized_series (content_type, works DESC, title);

-- Every series of a site of a work, bound to the normalized series it is of
CREATE TABLE site_series (
    source     VARCHAR(100)             NOT NULL,
    series_key VARCHAR(200)             NOT NULL,
    normalized BIGINT                   NOT NULL,
    bound_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, series_key),
    CONSTRAINT site_series_normalized_key FOREIGN KEY (normalized) REFERENCES normalized_series (id) ON DELETE CASCADE
);
CREATE INDEX site_series_normalized ON site_series (normalized);

-- The normalized series of every normalized work of one
CREATE TABLE normalized_series_work (
    work   BIGINT NOT NULL PRIMARY KEY,
    series BIGINT NOT NULL,
    CONSTRAINT normalized_series_work_work FOREIGN KEY (work) REFERENCES normalized_work (id) ON DELETE CASCADE,
    CONSTRAINT normalized_series_work_series FOREIGN KEY (series) REFERENCES normalized_series (id) ON DELETE CASCADE
);
CREATE INDEX normalized_series_work_series ON normalized_series_work (series);
