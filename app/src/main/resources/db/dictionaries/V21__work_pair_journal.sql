-- The journal of the user's words on two items being one work or not, the newest last: every word said
-- (one work, different works, a translation, a part) and every word taken back (answer none), with the
-- word the pair had before (none - no word), by the two items as they were pressed. What the user
-- undoes a word by, the pair given back the word before. Restored: written of what was kept before the
-- journal was, its time the kept one, the pair one item of each work, the word before unknown
CREATE TABLE work_pair_journal (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    said_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    source        VARCHAR(100)             NOT NULL,
    item          VARCHAR(200)             NOT NULL,
    other_source  VARCHAR(100)             NOT NULL,
    other_item    VARCHAR(200)             NOT NULL,
    answer        VARCHAR(20),
    answer_before VARCHAR(20),
    restored      BOOLEAN DEFAULT FALSE    NOT NULL
);
CREATE INDEX work_pair_journal_said_at ON work_pair_journal (said_at);

-- The words kept on two works: of each work the item bound to it first - no item of it bound before
INSERT INTO work_pair_journal (said_at, source, item, other_source, other_item, answer, restored)
SELECT r.said_at, a.source, a.item, b.source, b.item, r.kind, TRUE
FROM normalized_work_relation r
JOIN site_work a ON a.normalized = r.first_work
JOIN site_work b ON b.normalized = r.other_work
WHERE NOT EXISTS (SELECT 1 FROM site_work e WHERE e.normalized = a.normalized
        AND (e.bound_at < a.bound_at OR e.bound_at = a.bound_at AND (e.source < a.source OR e.source = a.source AND e.item < a.item)))
    AND NOT EXISTS (SELECT 1 FROM site_work e WHERE e.normalized = b.normalized
        AND (e.bound_at < b.bound_at OR e.bound_at = b.bound_at AND (e.source < b.source OR e.source = b.source AND e.item < b.item)));

-- The works of several items: every item but the one bound first said one work with it, when it was bound to it
INSERT INTO work_pair_journal (said_at, source, item, other_source, other_item, answer, restored)
SELECT o.bound_at, f.source, f.item, o.source, o.item, 'SAME', TRUE
FROM site_work o
JOIN site_work f ON f.normalized = o.normalized AND (f.source <> o.source OR f.item <> o.item)
WHERE NOT EXISTS (SELECT 1 FROM site_work e WHERE e.normalized = f.normalized
    AND (e.bound_at < f.bound_at OR e.bound_at = f.bound_at AND (e.source < f.source OR e.source = f.source AND e.item < f.item)));
