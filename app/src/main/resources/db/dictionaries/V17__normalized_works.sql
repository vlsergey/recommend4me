-- A work of the user's, whatever sites have it. What is of the work and not of a site's page of it
-- comes to stand on it
CREATE TABLE normalized_work (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

-- Every item of every site and the normalized work it is: at first one of its own, merged when the
-- user says two are one work. Several items of one site may be one work
CREATE TABLE site_work (
    source     VARCHAR(100)             NOT NULL,
    item       VARCHAR(200)             NOT NULL,
    normalized BIGINT                   NOT NULL REFERENCES normalized_work (id),
    bound_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, item)
);
CREATE INDEX site_work_normalized ON site_work (normalized);

-- The user's word on two normalized works, the smaller id first: different works, one the translation
-- of the other, one a part of the other. Works so related stay two
CREATE TABLE normalized_work_relation (
    first_work BIGINT                   NOT NULL REFERENCES normalized_work (id) ON DELETE CASCADE,
    other_work BIGINT                   NOT NULL REFERENCES normalized_work (id) ON DELETE CASCADE,
    kind       VARCHAR(20)              NOT NULL,
    said_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (first_work, other_work)
);
