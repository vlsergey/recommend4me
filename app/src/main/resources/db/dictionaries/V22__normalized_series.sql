-- The works the user said to be one series ("one series" of two works), a group of them by its id; a
-- work is in one group at most. A normalized series is made of the groups and of the series of the
-- sites on reading: every one of them sharing a normalized work with another is one series with it —
-- a work is of one series
CREATE TABLE series_group (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    made_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE series_group_work (
    work    BIGINT                   NOT NULL PRIMARY KEY REFERENCES normalized_work (id) ON DELETE CASCADE,
    series  BIGINT                   NOT NULL REFERENCES series_group (id) ON DELETE CASCADE,
    said_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX series_group_work_series ON series_group_work (series);
