-- THE CHANGES OF THE DICTIONARIES the documents of the works are drafted by, as they are written (draft.DictionaryChanges;
-- 2026-11-23): a universe or a tag whose meaning to its works changed — bound, merged, put under another, its entries'
-- statements or characters read anew — or a site's fandom or tag bound anew; the index of the list writes anew the
-- documents of the works having them, from the last change it took (worklist.ListIndexing).
CREATE TABLE dictionary_change (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(20)  NOT NULL,
    source     VARCHAR(100),
    value_key  VARCHAR(500) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- The statements of the entries and of their characters found by their values, any case alike: what the drafts of a few
-- works ask of them, not every statement
ALTER TABLE universe_property ADD COLUMN value_lower VARCHAR(2000) GENERATED ALWAYS AS (LOWER(property_value));
CREATE INDEX universe_property_value ON universe_property (catalogue, property, value_lower);
ALTER TABLE universe_character_property ADD COLUMN value_lower VARCHAR(2000) GENERATED ALWAYS AS (LOWER(property_value));
CREATE INDEX universe_character_property_value ON universe_character_property (catalogue, property, value_lower);

-- The entries a character is of, by the character
CREATE INDEX universe_character_of ON universe_character (catalogue, character_id);
